#include "device_id.h"

#include <stdbool.h>

#include <zephyr/drivers/hwinfo.h>

/*****************************************************************************
 * Definitions
 *****************************************************************************/

/*****************************************************************************
 * Variables
 *****************************************************************************/

/*****************************************************************************
 * Prototypes
 *****************************************************************************/

/*****************************************************************************
 * Functions
 *****************************************************************************/

uint32_t device_id(void)
{
    static bool fetched = false;
    static uint32_t id = 0;

    if (fetched == false) {
        hwinfo_get_device_id((void *)&id, sizeof(id));
        fetched = true;
    }

    return id;
}
